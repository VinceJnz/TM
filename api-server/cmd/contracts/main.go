// contracts generates frontend finance DTOs and an OpenAPI schema from the
// server's actual read/write types. Run with -check in CI to reject drift.
package main

import (
	"api-server/v2/internal/fieldrules"
	"api-server/v2/modelMethods/paymentLedger"
	"api-server/v2/models"
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"github.com/shopspring/decimal"
	"go/format"
	"os"
	"path/filepath"
	"reflect"
	"strings"
	"time"
)

type definition struct {
	Name  string
	Type  reflect.Type
	Write bool
}

func generate() (map[string][]byte, error) {
	types := []definition{{"Payment", reflect.TypeOf(models.UserPayments{}), false}, {"Refund", reflect.TypeOf(models.PaymentRefund{}), false}, {"PaymentWrite", reflect.TypeOf(paymentLedger.PaymentWrite{}), true}, {"RefundWrite", reflect.TypeOf(paymentLedger.RefundWrite{}), true}}
	types = append(types, definition{"BookingDTO", reflect.TypeOf(models.Booking{}), false}, definition{"MyBookingDTO", reflect.TypeOf(models.MyBooking{}), false}, definition{"TripDTO", reflect.TypeOf(models.Trip{}), false}, definition{"TripReportDTO", reflect.TypeOf(models.TripParticipantStatus{}), false}, definition{"BookingWrite", reflect.TypeOf(models.BookingWrite{}), true}, definition{"TripWrite", reflect.TypeOf(models.TripWrite{}), true})
	types = append(types, definition{"TripCostDTO", reflect.TypeOf(models.TripCost{}), false}, definition{"TripCostGroupDTO", reflect.TypeOf(models.TripCostGroup{}), false}, definition{"TripCostWrite", reflect.TypeOf(models.TripCostWrite{}), true}, definition{"TripCostGroupWrite", reflect.TypeOf(models.TripCostGroupWrite{}), true})
	types = append(types, definition{"GroupResourceDTO", reflect.TypeOf(models.GroupResource{}), false}, definition{"UserGroupDTO", reflect.TypeOf(models.UserGroup{}), false}, definition{"GroupResourceWrite", reflect.TypeOf(models.GroupResourceWrite{}), true}, definition{"UserGroupWrite", reflect.TypeOf(models.UserGroupWrite{}), true})
	types = append(types, definition{"GroupDTO", reflect.TypeOf(models.Group{}), false}, definition{"GroupWrite", reflect.TypeOf(models.GroupWrite{}), true}, definition{"ProfileDTO", reflect.TypeOf(models.ProfileDTO{}), false}, definition{"ProfileWrite", reflect.TypeOf(models.ProfileWrite{}), true}, definition{"EmailChangeRequest", reflect.TypeOf(models.EmailChangeRequest{}), true}, definition{"EmailChangeProof", reflect.TypeOf(models.EmailChangeProof{}), true})
	types = append(types, definition{"AccountDTO", reflect.TypeOf(models.AccountDTO{}), false}, definition{"AccountWrite", reflect.TypeOf(models.AccountWrite{}), true})
	var source bytes.Buffer
	source.WriteString("// Code generated by api-server/cmd/contracts; DO NOT EDIT.\npackage api\nimport (\"time\";\"github.com/shopspring/decimal\")\n")
	schemas := map[string]any{}
	for _, definition := range types {
		if err := fieldrules.ValidateType(definition.Type); err != nil {
			return nil, err
		}
		fmt.Fprintf(&source, "type %s struct {\n", definition.Name)
		properties := map[string]any{}
		for i := 0; i < definition.Type.NumField(); i++ {
			field := definition.Type.Field(i)
			tag := field.Tag.Get("json")
			name := strings.Split(tag, ",")[0]
			if name == "" || name == "-" {
				continue
			}
			goType := ""
			schema := map[string]any{}
			nullable := strings.Contains(field.Type.PkgPath(), "guregu/null")
			switch {
			case field.Type == reflect.TypeOf(decimal.NullDecimal{}):
				goType = "decimal.Decimal"
				schema["type"] = "string"
				schema["description"] = "Exact decimal encoded as a JSON string"
				nullable = true
			case field.Type.Name() == "Int":
				goType = "int"
				schema["type"] = "integer"
			case field.Type.Name() == "Float":
				goType = "float64"
				schema["type"] = "number"
			case field.Type == reflect.TypeOf(models.Money{}):
				goType = "float64"
				schema["type"] = "number"
				schema["description"] = "Exact decimal on the server; NZD major units. Browser values are display/input only."
			case field.Type == reflect.TypeOf(time.Time{}) || field.Type.Name() == "Time":
				goType = "time.Time"
				schema["type"] = "string"
				schema["format"] = "date-time"
			case field.Type.Kind() == reflect.Int:
				goType = "int"
				schema["type"] = "integer"
			case field.Type.Kind() == reflect.Bool:
				goType = "bool"
				schema["type"] = "boolean"
			case field.Type.Kind() == reflect.String || field.Type.Name() == "String":
				goType = "string"
				schema["type"] = "string"
			default:
				return nil, fmt.Errorf("unsupported contract type %s", field.Type)
			}
			if nullable {
				schema["type"] = []string{schema["type"].(string), "null"}
			}
			properties[name] = schema
			fmt.Fprintf(&source, "%s %s `json:%q`\n", field.Name, goType, tag)
		}
		source.WriteString("}\n")
		schemas[definition.Name] = map[string]any{"type": "object", "properties": properties}
		if definition.Write {
			applyWriteRules(definition.Type, schemas[definition.Name].(map[string]any), properties)
		}
	}
	paths := map[string]any{}
	for _, resource := range []struct{ Path, Read, Write string }{{"payments", "Payment", "PaymentWrite"}, {"refunds", "Refund", "RefundWrite"}, {"bookings", "BookingDTO", "BookingWrite"}, {"myBookings", "MyBookingDTO", "BookingWrite"}, {"trips", "TripDTO", "TripWrite"}, {"tripsReport", "TripReportDTO", ""}, {"tripCosts", "TripCostDTO", "TripCostWrite"}, {"tripCostGroups", "TripCostGroupDTO", "TripCostGroupWrite"}, {"users", "AccountDTO", "AccountWrite"}, {"securityGroup", "GroupDTO", "GroupWrite"}, {"securityGroupResource", "GroupResourceDTO", "GroupResourceWrite"}, {"securityUserGroup", "UserGroupDTO", "UserGroupWrite"}} {
		ref := func(name string) map[string]any { return map[string]any{"$ref": "#/components/schemas/" + name} }
		jsonContent := func(schema any) map[string]any {
			return map[string]any{"application/json": map[string]any{"schema": schema}}
		}
		request := map[string]any{"required": true, "content": jsonContent(ref(resource.Write))}
		listResponse := map[string]any{"description": "Bounded array; single-record GET also returns an array", "content": jsonContent(map[string]any{"type": "array", "items": ref(resource.Read)})}
		responses := map[string]any{"200": listResponse, "401": map[string]any{"description": "Session required"}, "403": map[string]any{"description": "Resource capability and supported scope required"}}
		if resource.Path == "bookings" || resource.Path == "myBookings" {
			responses["403"] = map[string]any{"description": "Resource capability required; own scope is enforced in SQL"}
		}
		parameters := []any{map[string]any{"name": "limit", "in": "query", "schema": map[string]any{"type": "integer", "minimum": 1, "maximum": 500, "default": 100}}, map[string]any{"name": "offset", "in": "query", "schema": map[string]any{"type": "integer", "minimum": 0, "maximum": 1000000}}}
		if resource.Write == "" {
			paths["/"+resource.Path] = map[string]any{"get": map[string]any{"parameters": parameters, "responses": responses}}
			continue
		}
		paths["/"+resource.Path] = map[string]any{"get": map[string]any{"responses": responses}, "post": map[string]any{"requestBody": request, "responses": map[string]any{"201": map[string]any{"description": "Created ID", "content": jsonContent(map[string]any{"type": "integer"})}}}}
		paths["/"+resource.Path+"/{id}"] = map[string]any{
			"parameters": []any{map[string]any{"name": "id", "in": "path", "required": true, "schema": map[string]any{"type": "integer", "minimum": 1}}},
			"get":        map[string]any{"responses": responses},
			"put":        map[string]any{"requestBody": request, "responses": map[string]any{"200": map[string]any{"description": "Updated record", "content": jsonContent(ref(resource.Read))}, "409": map[string]any{"description": "Operation conflicts with existing data or immutable financial state"}}},
			"delete":     map[string]any{"responses": map[string]any{"200": map[string]any{"description": "Deleted record"}, "409": map[string]any{"description": "Provider records are immutable"}}},
		}
		collection := paths["/"+resource.Path].(map[string]any)
		collection["get"].(map[string]any)["parameters"] = append(parameters, map[string]any{"name": "pagination", "in": "query", "schema": map[string]any{"type": "string", "enum": []string{"offset", "cursor"}}}, map[string]any{"name": "after", "in": "query", "schema": map[string]any{"type": "integer", "minimum": 0}})
		if resource.Path == "payments" || resource.Path == "refunds" {
			for _, method := range []string{"put", "delete"} {
				paths["/"+resource.Path+"/{id}"].(map[string]any)[method].(map[string]any)["parameters"] = []any{map[string]any{"name": "X-Change-Reason", "in": "header", "required": true, "schema": map[string]any{"type": "string", "minLength": 1, "maxLength": 500}}}
			}
		}
	}
	addProfilePaths(paths)
	decorateOperations(paths)
	paths["/trips/{id}/bookings"] = map[string]any{"parameters": []any{map[string]any{"name": "id", "in": "path", "required": true, "schema": map[string]any{"type": "integer", "minimum": 1}}}, "get": paths["/bookings"].(map[string]any)["get"]}
	doc := map[string]any{"openapi": "3.1.0", "info": map[string]any{"title": "Trip Manager resource API", "version": "1", "description": "Paths are relative to configured API prefix. Manual writes never issue provider charges or refunds. Additional legacy fields are ignored by write DTOs."}, "paths": paths, "security": []any{map[string]any{"session": []string{}}}, "components": map[string]any{"schemas": schemas, "securitySchemes": map[string]any{"session": map[string]any{"type": "apiKey", "in": "cookie", "name": "session"}}}}
	schema, err := json.MarshalIndent(doc, "", "  ")
	if err != nil {
		return nil, err
	}
	code, err := format.Source(source.Bytes())
	if err != nil {
		return nil, err
	}
	return map[string][]byte{"client1/app/api/finance_generated.go": code, "api-server/contracts/finance.openapi.json": append(schema, '\n')}, nil
}

func main() {
	check := flag.Bool("check", false, "fail if generated contracts differ")
	root := flag.String("root", "..", "repository root")
	flag.Parse()
	outputs, err := generate()
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	for name, data := range outputs {
		path := filepath.Join(*root, filepath.FromSlash(name))
		if *check {
			old, err := os.ReadFile(path)
			if err != nil || !bytes.Equal(bytes.ReplaceAll(old, []byte("\r\n"), []byte("\n")), data) {
				fmt.Fprintln(os.Stderr, "contract drift:", name)
				os.Exit(1)
			}
			continue
		}
		if err = os.MkdirAll(filepath.Dir(path), 0755); err == nil {
			err = os.WriteFile(path, data, 0644)
		}
		if err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}
}
