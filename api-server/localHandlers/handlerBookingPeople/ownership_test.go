func TestParticipantOwnershipReadsAndForgedUpdate(t *testing.T) {
	db := testdb.Open(t, testdb.Bookings+`UPDATE at_booking_people SET notes=NULL WHERE id=111;`)
	app := &appCore.Config{Db: db, SessionIDKey: "test-session"}
	h := New(app)
	own := mux.SetURLVars(httptest.NewRequest("GET", "/", nil), map[string]string{"id": "11"})
	own = own.WithContext(context.WithValue(own.Context(), app.SessionIDKey, &models.Session{UserID: 1, AccessScope: "own"}))
	response := httptest.NewRecorder()
	h.GetList(response, own)
	if response.Code != 200 || !strings.Contains(response.Body.String(), `"notes":""`) {
		t.Fatalf("legacy participant notes: %d %s", response.Code, response.Body.String())
	}
	for _, scope := range []string{"own", "any"} {
		for _, method := range []string{"all", "nested", "item"} {
			id := "222"
			if method == "nested" {
				id = "22"
			}
			r := mux.SetURLVars(httptest.NewRequest("GET", "/", nil), map[string]string{"id": id})
			r = r.WithContext(context.WithValue(r.Context(), app.SessionIDKey, &models.Session{UserID: 1, AccessScope: scope}))
			w := httptest.NewRecorder()
			switch method {
			case "all":
				h.GetAll(w, r)
			case "nested":
				h.GetList(w, r)
			case "item":
				h.Get(w, r)
			}
			if w.Code != 200 {
				t.Fatalf("%s/%s: %d %s", scope, method, w.Code, w.Body.String())
			}
			if strings.Contains(w.Body.String(), `"owner_id":2`) != (scope == "any") {
				t.Fatalf("ownership leak: %s", w.Body.String())
			}
		}
	}
	// A caller supplies their own booking_id while targeting someone else's participant.
	r := mux.SetURLVars(httptest.NewRequest("PUT", "/", strings.NewReader(`{"booking_id":11,"person_id":1,"notes":"forged"}`)), map[string]string{"id": "222"})
	r = r.WithContext(context.WithValue(r.Context(), app.SessionIDKey, &models.Session{UserID: 1, AccessScope: "own"}))
	w := httptest.NewRecorder()
	h.Update(w, r)
	var notes string
	if err := db.Get(&notes, "SELECT notes FROM at_booking_people WHERE id=222"); err != nil {
		t.Fatal(err)
	}
	if notes != "second" {
		t.Fatal("forged parent bypassed ownership")
	}
}

func TestParticipantInsertChecksActualParentAtWriteTime(t *testing.T) {
	db := testdb.Open(t, testdb.Bookings+`ALTER TABLE at_booking_people ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;`)
	var id int
	if err := db.QueryRow(qryCreate, 1, 22, 1, "forged parent", "own").Scan(&id); err != sql.ErrNoRows {
		t.Fatalf("cross-user insert returned %v", err)
	}
	if _, err := db.Exec("UPDATE at_bookings SET stripe_session_id='checkout' WHERE id=11"); err != nil {
		t.Fatal(err)
	}
	if err := db.QueryRow(qryCreate, 1, 11, 1, "after checkout", "own").Scan(&id); err != sql.ErrNoRows {
		t.Fatalf("insert after checkout returned %v", err)
	}
	if _, err := db.Exec("UPDATE at_bookings SET stripe_session_id=NULL WHERE id=11"); err != nil {
		t.Fatal(err)
	}
	if err := db.QueryRow(qryCreate, 1, 11, 1, "allowed", "own").Scan(&id); err != nil {
		t.Fatal(err)
	}
	if _, err := db.Exec("INSERT INTO at_payments (id, booking_id) VALUES (1,11)"); err != nil {
		t.Fatal(err)
	}
	if err := db.QueryRow(qryCreate, 1, 11, 1, "payment history", "own").Scan(&id); err != sql.ErrNoRows {
		t.Fatalf("insert with payment history returned %v", err)
	}
}
