func TestBookingServiceEnforcesOwnerAndLockedTripDates(t *testing.T) {
	db := testdb.Open(t, testdb.Bookings)
	service := Service{Store: store.Store{DB: db}}
	ctx := context.Background()
	input := models.Booking{ID: 22, Notes: "attempt", FromDate: time.Date(2026, 1, 1, 0, 0, 0, 0, time.UTC), ToDate: time.Date(2026, 1, 2, 0, 0, 0, 0, time.UTC)}
	if _, err := service.Save(ctx, 1, false, "update", input); !errors.Is(err, sql.ErrNoRows) {
		t.Fatal("another owner editable", err)
	}
	input.ID = 11
	input.ToDate = input.FromDate
	if _, err := service.Save(ctx, 1, false, "update", input); !errors.Is(err, ErrValidation) {
		t.Fatal("equal booking dates accepted", err)
	}
	input.ToDate = time.Date(2031, 1, 1, 0, 0, 0, 0, time.UTC)
	if _, err := service.Save(ctx, 1, false, "update", input); !errors.Is(err, ErrValidation) {
		t.Fatal("booking outside trip accepted", err)
	}
	var notes string
	if err := db.Get(&notes, `SELECT notes FROM at_bookings WHERE id=11`); err != nil || notes != "first" {
		t.Fatal("failed validation mutated booking", notes, err)
	}
	input.ToDate = time.Date(2026, 1, 2, 0, 0, 0, 0, time.UTC)
	if _, err := service.Save(ctx, 1, false, "update", input); err != nil {
		t.Fatal(err)
	}
	input.OwnerID = 1
	input.TripID.Int64 = 1
	input.TripID.Valid = true
	input.PreserveBookingPrice = true
	if _, err := service.Save(ctx, 1, true, "update", input); err != nil {
		t.Fatal(err)
	}
	var booking models.Booking
	if err := db.Get(&booking, `SELECT booking_price FROM at_bookings WHERE id=11`); err != nil || !booking.BookingPrice.Valid || booking.BookingPrice.Decimal.String() != "10" {
		t.Fatal("details update changed the stored price", booking.BookingPrice, err)
	}
	// Holding the parent lock must cancel the entire workflow, not validate
	// against unlocked dates and commit later.
	blocker, err := db.Beginx()
	if err != nil {
		t.Fatal(err)
	}
	defer blocker.Rollback()
	if _, err = blocker.Exec(`SELECT id FROM at_trips WHERE id=1 FOR UPDATE`); err != nil {
		t.Fatal(err)
	}
	canceled, cancel := context.WithTimeout(ctx, 100*time.Millisecond)
	defer cancel()
	if _, err = service.Save(canceled, 1, false, "update", input); err == nil {
		t.Fatal("ignored parent lock cancellation")
	}
}

func TestBookingDraftStoresNormalizedVoucher(t *testing.T) {
	db := testdb.Open(t, testdb.Bookings+`
		ALTER TABLE at_bookings ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 100);
		INSERT INTO at_booking_vouchers(code,discount_percent,fixed_cost,expiry_date,is_active) VALUES('WELCOME',15,NULL,CURRENT_DATE+30,true);
	`)
	service := Service{Store: store.Store{DB: db}}
	ctx := context.Background()
	code := " welcome "
	input := models.Booking{Notes: "Voucher booking", VoucherInput: &code,
		FromDate: time.Date(2026, 1, 1, 0, 0, 0, 0, time.UTC), ToDate: time.Date(2026, 1, 2, 0, 0, 0, 0, time.UTC)}
	input.TripID.Int64, input.TripID.Valid = 1, true
	saved, err := service.Save(ctx, 1, false, "create", input)
	if err != nil {
		t.Fatal(err)
	}
	var stored models.Booking
	if err := db.Get(&stored, `SELECT voucher_code,booking_price FROM at_bookings WHERE id=$1`, saved.ID); err != nil || stored.VoucherCode != "WELCOME" || stored.BookingPrice.Valid {
		t.Fatalf("unexpected voucher draft: %q, %v, %v", stored.VoucherCode, stored.BookingPrice, err)
	}
	code = "missing"
	if _, err := service.Save(ctx, 1, false, "create", input); !errors.Is(err, ErrVoucher) {
		t.Fatalf("unknown voucher accepted: %v", err)
	}
	input.ID = saved.ID
	code = ""
	if _, err := service.Save(ctx, 1, false, "update", input); err != nil {
		t.Fatal(err)
	}
	if err := db.Get(&stored, `SELECT voucher_code FROM at_bookings WHERE id=$1`, saved.ID); err != nil || stored.VoucherCode != "" {
		t.Fatalf("voucher was not cleared: %q, %v", stored.VoucherCode, err)
	}
}
