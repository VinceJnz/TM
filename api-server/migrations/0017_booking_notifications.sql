CREATE TABLE IF NOT EXISTS at_notification_outbox(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 booking_id integer NOT NULL REFERENCES at_bookings(id) ON DELETE RESTRICT,
 kind text NOT NULL,
 recipient text NOT NULL,
 subject text NOT NULL,
 body text NOT NULL,
 attempts integer NOT NULL DEFAULT 0,
 available_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 created timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 sent_at timestamptz,
 UNIQUE(booking_id,kind)
);
CREATE INDEX IF NOT EXISTS notification_outbox_due ON at_notification_outbox(available_at,id) WHERE sent_at IS NULL;
